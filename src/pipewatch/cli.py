@main.command()
@click.argument("script_path", type=click.Path(exists=True, path_type=Path))
@click.option(
    "--output", "-o",
    type=click.Path(path_type=Path),
    help="Output path for instrumented script (default: script_path.instrumented)"
)
@click.option(
    "--step-prefix",
    default="step",
    help="Prefix for auto-detected step names"
)
@click.option(
    "--obsrun-path",
    default="obsrun",
    help="Path to obsrun executable (default: obsrun in PATH)"
)
def wrap(
    script_path: Path,
    output: Path | None,
    step_prefix: str,
    obsrun_path: str,
) -> None:
    """Generate an instrumented copy of a run.sh script.

    This command minimally rewrites srun commands in the script to wrap
    execution with obsrun for observability.

    Example:
        pipewatch wrap run.sh -o run_instrumented.sh
    """
    output_path = output or script_path.with_suffix(".instrumented.sh")

    click.echo(f"Reading script: {script_path}")
    content = script_path.read_text()

    # Find the shebang line
    lines = content.splitlines(keepends=True)
    shebang_idx = 0
    for i, line in enumerate(lines):
        if line.startswith("#!"):
            shebang_idx = i + 1
            break

    # Generate obsrun sourcing
    obsrun_setup = f'''
# === Pipewatch instrumentation ===
# Auto-generated by pipewatch wrap
export PIPEWATCH_OBSRUN_PATH="{shutil.which(obsrun_path) or obsrun_path}"
export PIPEWATCH_STEP_PREFIX="{step_prefix}"

# Function to wrap srun with obsrun
_pipewatch_obsrun_wrap() {{
    local cmd="$1"
    shift
    local step_name="${{PIPEWATCH_STEP_PREFIX}}_${{PIPEWATCH_STEP_COUNT:-0}}"
    export PIPEWATCH_STEP_COUNT=$(( ${{PIPEWATCH_STEP_COUNT:-0}} + 1 ))
    
    # Detect output/error paths from srun args
    local output_path=""
    local error_path=""
    local job_name=""
    local args=("$@")
    
    for i in "${{!args[@]}}"; do
        case "${{args[$i]}}" in
            --output|-o) output_path="${{args[$((i+1))]}}" ;;
            --error|-e) error_path="${{args[$((i+1))]}}" ;;
            --job-name|-J) job_name="${{args[$((i+1))]}}" ;;
        esac
    done
    
    # Run through obsrun
    if [ -n "$PIPEWATCH_OBSRUN_PATH" ] && [ -x "$PIPEWATCH_OBSRUN_PATH" ]; then
        PIPEWATCH_STEP_NAME="$step_name" \\
        PIPEWATCH_SAMPLE_ID="${{SLURM_ARRAY_TASK_ID:-}}" \\
        PIPEWATCH_STDOUT_PATH="$output_path" \\
        PIPEWATCH_STDERR_PATH="$error_path" \\
        "$PIPEWATCH_OBSRUN_PATH" "$cmd"
    else
        eval "$cmd"
    fi
}}

# Wrapper for srun to instrument commands
pipewatch_srun() {{
    local srun_args=()
    local cmd=""
    local in_cmd=false
    
    for arg in "$@"; do
        if [ "$in_cmd" = true ] || [[ "$arg" == bash* ]] || [[ "$arg" == sh* ]]; then
            in_cmd=true
            cmd="$cmd $arg"
        else
            srun_args+=("$arg")
        fi
    done
    
    if [ -n "$cmd" ]; then
        # Wrap the command
        _pipewatch_obsrun_wrap "${{cmd:1}}" "${{srun_args[@]}}"
    else
        command srun "$@"
    fi
}}

# Alias srun if not already wrapped
if ! type srun | grep -q pipewatch; then
    alias srun=pipewatch_srun
fi

# === End Pipewatch instrumentation ===

'''

    # Insert after shebang and any initial comments
    instrumented_lines = lines[:shebang_idx]
    instrumented_lines.append(obsrun_setup)
    instrumented_lines.extend(lines[shebang_idx:])

    # Also try to instrument direct srun bash -c calls
    instrumented_content = "".join(instrumented_lines)
    
    # Pattern to find srun bash -c "..." and wrap it
    # This is a simplified instrumentation that catches common patterns
    instrumented_content = re.sub(
        r'srun\s+(.*?)(bash\s+-c\s+["\'])([^"\']+)(["\'])',
        lambda m: f'srun {m.group(1)}bash -c \'eval "$PIPEWATCH_OBSRUN_PATH" "{m.group(3)}"\' {m.group(4)}',
        instrumented_content
    )

    output_path.write_text(instrumented_content)
    output_path.chmod(0o755)

    click.echo(f"Instrumented script written to: {output_path}")
    click.echo("Note: This is a best-effort instrumentation. Manual review recommended.")


def _has_gnu_time(time_cmd: str = "/usr/bin/time") -> bool:
    """Check if the time command is GNU time (supports -v flag)."""
    try:
        result = subprocess.run(
            [time_cmd, "--version"],
            capture_output=True,
            text=True,
            timeout=5,
        )
        return "GNU" in result.stdout
    except (subprocess.SubprocessError, FileNotFoundError):
        return False


@main.command()
@click.argument("command", nargs=-1, required=True)
@click.option(
    "--output", "-o",
    type=click.Path(path_type=Path),
    default="pipewatch-events.ndjson",
    help="Output path for event file"
)
@click.option(
    "--step-name",
    help="Name of the step being executed"
)
@click.option(
    "--sample-id",
    help="Sample identifier (auto-detected from SLURM_ARRAY_TASK_ID if not set)"
)
@click.option(
    "--stdout-path",
    help="Path to stdout log file"
)
@click.option(
    "--stderr-path",
    help="Path to stderr log file"
)
@click.option(
    "--capture-resources/--no-capture-resources",
    default=True,
    help="Capture resource usage with /usr/bin/time -v"
)
@click.option(
    "--use-time",
    default="/usr/bin/time",
    help="Path to time command (default: /usr/bin/time)"
)
def run(
    command: tuple[str, ...],
    output: Path,
    step_name: str | None,
    sample_id: str | None,
    stdout_path: str | None,
    stderr_path: str | None,
    capture_resources: bool,
    use_time: str,
) -> None:
    """Execute a command under observation.

    This command runs the specified command with full observability,
    capturing exit codes, resource usage, and SLURM environment.

    Example:
        pipewatch run --step-name align "bwa mem ref.fa reads.fq | samtools sort -o out.bam"
    """
    cmd_str = " ".join(command)
    
    # Auto-detect sample ID from SLURM_ARRAY_TASK_ID
    if sample_id is None:
        sample_id = os.environ.get("SLURM_ARRAY_TASK_ID")
    
    # Auto-detect step name from environment
    if step_name is None:
        step_name = os.environ.get("PIPEWATCH_STEP_NAME")

    # Use provided stdout/stderr paths or from environment
    stdout_path = stdout_path or os.environ.get("PIPEWATCH_STDOUT_PATH")
    stderr_path = stderr_path or os.environ.get("PIPEWATCH_STDERR_PATH")

    click.echo(f"Running: {cmd_str}", err=True)

    with EventCollector(output, stdout_path=stdout_path, stderr_path=stderr_path) as collector:
        # Record start
        collector.record_start(
            command=cmd_str,
            step_name=step_name,
            sample_id=sample_id,
        )

        # Prepare command with time -v if requested and available
        has_gnu = _has_gnu_time(use_time)
        if capture_resources and shutil.which(use_time) and has_gnu:
            # Create temp files for time output
            time_output = tempfile.NamedTemporaryFile(mode="w+", delete=False, suffix=".time")
            time_output.close()
            
            # Wrap command with time -v
            wrapped_cmd = f'{use_time} -v -o "{time_output.name}" bash -c {shlex.quote(f"set -euo pipefail; {cmd_str}")}'
        else:
            if capture_resources and not has_gnu:
                click.echo(
                    f"Note: {use_time} is not GNU time, resource capture disabled. "
                    "Install GNU time for resource metrics.",
                    err=True,
                )
            wrapped_cmd = f'bash -c {shlex.quote(f"set -euo pipefail; {cmd_str}")}'
            time_output = None

        # Execute command
        try:
            result = subprocess.run(
                wrapped_cmd,
                shell=True,
                capture_output=False,
            )
            exit_code = result.returncode
        except Exception as e:
            click.echo(f"Error executing command: {e}", err=True)
            exit_code = 126  # Command invoked cannot execute

        # Parse resource usage if captured
        resource_usage: dict[str, Any] | None = None
        if time_output:
            try:
                time_data = Path(time_output.name).read_text()
                resource_usage = TimeVParser.parse(time_data).to_resource_usage()
            except Exception:
                pass
            finally:
                try:
                    os.unlink(time_output.name)
                except OSError:
                    pass

        # Try to get SLURM accounting data if available
        slurm_job_id = os.environ.get("SLURM_JOB_ID")
        if slurm_job_id:
            accounting = SlurmAccounting()
            sacct_data = accounting.get_job_stats(slurm_job_id)
            if sacct_data and not resource_usage:
                # Use sacct data if time -v didn't work
                resource_usage = {
                    "max_rss_kb": sacct_data.max_rss_mb * 1024 if sacct_data.max_rss_mb else None,
                }

        # Record end
        collector.record_end(
            exit_code=exit_code,
            resource_usage=resource_usage,
        )

    click.echo(f"Events written to: {output}", err=True)
    sys.exit(exit_code)


@main.command()
@click.argument("paths", nargs=-1, required=True, type=click.Path(exists=True, path_type=Path))
@click.option(
    "--output", "-o",
    type=click.Path(path_type=Path),
    default="pipewatch-report",
    help="Output directory for report files"
)
@click.option(
    "--format",
    type=click.Choice(["html", "json", "both"]),
    default="both",
    help="Output format"
)
@click.option(
    "--compare-with",
    type=click.Path(exists=True, path_type=Path),
    help="Path to baseline event file for comparison"
)
@click.option(
    "--job-named/--no-job-named",
    default=False,
    help="Name reports using job ID (e.g., slurm-12345.html instead of index.html)"
)
def report(
    paths: tuple[Path, ...],
    output: Path,
    format: str,
    compare_with: Path | None,
    job_named: bool,
) -> None:
    """Generate HTML/JSON report from event files.

    This command ingests one or more event files and produces
    a comprehensive observability report.

    Example:
        pipewatch report pipewatch-events.ndjson
        pipewatch report runs/*.ndjson -o report/
    """
    click.echo(f"Analyzing {len(paths)} event file(s)...")

    # Expand directories
    all_paths: list[Path] = []
    for path in paths:
        if path.is_dir():
            all_paths.extend(path.glob("**/*.ndjson"))
        else:
            all_paths.append(path)

    if not all_paths:
        click.echo("No event files found.", err=True)
        sys.exit(1)

    # Analyze events
    analyzer = PipelineAnalyzer(all_paths)
    summary = analyzer.analyze()

    click.echo(f"Found {summary.total_steps} steps across {summary.total_samples} samples")
    click.echo(f"Total duration: {summary._format_duration(summary.total_duration_ms)}")
    click.echo(f"Failure rate: {summary.failure_rate * 100:.1f}%")

    # Comparison if requested
    comparison: dict[str, Any] | None = None
    if compare_with:
        click.echo(f"Comparing with baseline: {compare_with}")
        baseline_analyzer = PipelineAnalyzer([compare_with])
        comparison = analyzer.compare_runs(baseline_analyzer)

    # Generate output
    output.mkdir(parents=True, exist_ok=True)

    generator = HTMLReportGenerator()

    # Determine file names based on job_named flag
    if job_named:
        # Sanitize run_id for use in filename (remove/replace special chars)
        safe_run_id = "".join(c if c.isalnum() or c in "-_" else "_" for c in summary.run_id)
        html_filename = f"{safe_run_id}.html"
        json_filename = f"{safe_run_id}.json"
    else:
        html_filename = "index.html"
        json_filename = "data.json"

    if format in ("html", "both"):
        html_path = output / html_filename
        generator.generate(summary, html_path, comparison=comparison)
        click.echo(f"HTML report: {html_path}")

    if format in ("json", "both"):
        json_path = output / json_filename
        generator.generate_json(summary, json_path)
        click.echo(f"JSON data: {json_path}")


# Standalone obsreport command for backward compatibility
@click.command()
@click.argument("event_file", type=click.Path(exists=True, path_type=Path))
@click.option(
    "--output", "-o",
    type=click.Path(path_type=Path),
    help="Output HTML file path"
)
@click.option(
    "--json-output",
    type=click.Path(path_type=Path),
    help="Also output JSON to this path"
)
def obsreport_main(
    event_file: Path,
    output: Path | None,
    json_output: Path | None,
) -> None:
    """Legacy obsreport command - convert events to HTML report.

    This is a simplified interface for quick report generation.
    For full functionality, use 'pipewatch report'.
    """
    import shlex

    analyzer = PipelineAnalyzer([event_file])
    summary = analyzer.analyze()

    output_path = output or event_file.with_suffix(".html")
    json_path = json_output or output_path.with_suffix(".json")

    generator = HTMLReportGenerator()
    generator.generate(summary, output_path)
    generator.generate_json(summary, json_path)

    click.echo(f"Report generated: {output_path}")
    click.echo(f"JSON data: {json_path}")


if __name__ == "__main__":
    main()
